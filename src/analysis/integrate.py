from __future__ import annotations

import json
from pathlib import Path

import geopandas as gpd
import numpy as np
import pandas as pd

from src.collect.accidents import load_accidents
from src.collect.bulletin import load_bulletin_tables
from src.collect.holidays import load_holidays
from src.collect.imis import build_station_day_features, load_stations
from src.collect.regions import load_regions
from src.collect.weather import fetch_weather_for_regions
from src.paths import BULLETIN_START, FIGURES, PROCESSED, STUDY_END

# Output path for integration statistics and data quality metrics.
INTEGRATION_LOG = PROCESSED / "integration_log.json"


def assign_points_to_regions(
    points: pd.DataFrame,
    regions: gpd.GeoDataFrame,
    lon_col: str = "lon",
    lat_col: str = "lat",
) -> gpd.GeoDataFrame:
    """Assign geographical points to avalanche warning regions.

    Convert longitude and latitude coordinates into point geometries
    and perform a spatial join with the region polygons. Points outside
    the defined regions remain unmatched.
    """

    # Convert geographical coordinates into a GeoDataFrame using WGS84.
    gdf = gpd.GeoDataFrame(
        points.copy(),
        geometry=gpd.points_from_xy(points[lon_col], points[lat_col]),
        crs=4326,
    )

    # Assign each point to the region polygon containing it.
    # A left join preserves points without a matching region.
    joined = gpd.sjoin(
        gdf,
        regions[["region_id", "geometry"]],
        how="left",
        predicate="within",
    )

    # Remove the auxiliary index generated by the spatial join.
    if "index_right" in joined.columns:
        joined = joined.drop(columns=["index_right"])
    return joined


def aspect_in_critical(aspect: str | float | None, critical: str | float | None) -> int | None:
    """Check whether an accident occurred on a critical slope aspect.

    Returns:
        1: The accident aspect matches a critical aspect.
        0: The accident aspect does not match.
        None: Insufficient information for comparison.
    """

    # Return an unknown result if the accident aspect is missing.
    if aspect is None or (isinstance(aspect, float) and np.isnan(aspect)):
        return None

    # Return an unknown result if no critical aspects are available.
    if critical is None or (isinstance(critical, float) and np.isnan(critical)) or critical == "":
        return None

    # Convert pipe-separated aspects into a normalized set.
    aspects = {
        a.strip().upper()
        for a in str(critical).split("|")
        if a.strip()
    }

    # Check whether the accident aspect is listed as critical.
    return int(str(aspect).strip().upper() in aspects)


def elevation_in_critical(
    elev: float | None,
    elev_min: float | None,
    elev_max: float | None,
) -> int | None:
    """Check whether an accident occurred within a critical elevation range.

    Missing lower or upper bounds are interpreted as open-ended ranges.

    Returns:
        1: The accident elevation is within the critical range.
        0: The accident elevation is outside the critical range.
        None: The required elevation information is missing.
    """

    # An accident without elevation information cannot be evaluated.
    if elev is None or (isinstance(elev, float) and np.isnan(elev)):
        return None

    # Return an unknown result if neither boundary is specified.
    if elev_min is None and elev_max is None:
        return None

    # Replace missing elevation boundaries with infinity to support
    # open-ended ranges, such as elevations above a given threshold.
    lo = (
        -np.inf
        if elev_min is None
        or (isinstance(elev_min, float) and np.isnan(elev_min))
        else elev_min
    )
    hi = (
        np.inf
        if elev_max is None
        or (isinstance(elev_max, float) and np.isnan(elev_max))
        else elev_max
      )

    # Evaluate whether the accident elevation falls within the range.
    return int(lo <= float(elev) <= hi)


def build_integrated_tables(
    start: str = BULLETIN_START,
    end: str = STUDY_END,
    fetch_weather: bool = True,
    max_meteo_stations: int = 25,
) -> dict[str, pd.DataFrame]:
    """Build and persist the integrated datasets for avalanche analysis.

    Combine avalanche accidents, warning regions, avalanche bulletins,
    IMIS station measurements, weather observations and holiday data
    into a region-day fact table.

    Args:
        start: Start date of the study period.
        end: End date of the study period.
        fetch_weather: Whether to retrieve weather data or use cached data.
        max_meteo_stations: Intended maximum number of meteorological
            stations (currently unused).

    Returns:
        Dictionary containing the processed datasets and integration log.
    """

    # Ensure the output directory exists and initialize the integration log.
    PROCESSED.mkdir(parents=True, exist_ok=True)
    log: dict = {}

    # ------------------------------------------------------------------
    # 1. Avalanche warning regions
    # ------------------------------------------------------------------

    regions = load_regions()

    # Create a non-spatial region reference table containing identifiers,
    # administrative region classifications and geographical centroids.
    regions_tbl = pd.DataFrame(
        {
            "region_id": regions["region_id"],
            "major_region": regions["major_region"],
            "centroid_lon": regions["centroid_lon"],
            "centroid_lat": regions["centroid_lat"],
        }
    )
    log["n_regions"] = len(regions_tbl)

    # ------------------------------------------------------------------
    # 2. Avalanche accidents
    # ------------------------------------------------------------------

    accidents = load_accidents()
    log["accidents_raw"] = len(accidents)

    # Exclude accidents occurring before the study period begins.
    study = accidents[accidents["date"] >= start].copy()
    log["accidents_since_start"] = len(study)

    # Keep accidents with a coordinate uncertainty of at most 250 m.
    # Records with unknown coordinate quality are also retained.
    before_q = len(study)

    study = study[
        study["coordinates_quality"].isna() | (study["coordinates_quality"] <= 250)
    ].copy()

    log["accidents_dropped_coord_quality"] = before_q - len(study)

    # Remove accidents without geographical coordinates because they
    # cannot be assigned to an avalanche warning region.
    study = study.dropna(subset=["lat", "lon"])
    log["accidents_with_coords"] = len(study)

    # Spatially assign accidents to their corresponding warning regions.
    acc_joined = assign_points_to_regions(study, regions)

    # Record unmatched accidents before excluding them from the analysis.
    log["accidents_unmatched_region"] = int(
        acc_joined["region_id"].isna().sum()
    )

    acc_joined = acc_joined.dropna(subset=["region_id"])
    log["accidents_matched"] = len(acc_joined)

    # ------------------------------------------------------------------
    # 3. IMIS monitoring stations
    # ------------------------------------------------------------------

    stations = load_stations()

    # Assign monitoring stations to avalanche warning regions.
    st_joined = assign_points_to_regions(stations, regions)

    log["stations_total"] = len(stations)
    log["stations_unmatched_region"] = int(
        st_joined["region_id"].isna().sum()
    )

    # Remove spatial geometries to create a tabular station reference.
    stations_tbl = st_joined.drop(
        columns=["geometry"],
        errors="ignore"
    ).copy()

    # Represent the station activity status as a binary integer.
    stations_tbl["active"] = stations_tbl["active"].astype(int)
    # ------------------------------------------------------------------
    # 4. Avalanche bulletin data
    # ------------------------------------------------------------------

    # Load daily avalanche forecasts and individual avalanche problems
    # for the selected study period.
    bulletin, problems = load_bulletin_tables(
        start=start,
        end=end
    )

    log["bulletin_region_days"] = len(bulletin)
    log["bulletin_problem_rows"] = len(problems)

    # Enrich each accident with the critical slope conditions reported
    # in the avalanche bulletin for the corresponding region and date.
    acc = acc_joined.merge(
        bulletin[
            [
                "date",
                "region_id",
                "critical_aspects",
                "critical_elev_min",
                "critical_elev_max",
            ]
        ],
        on=["date", "region_id"],
        how="left",
    )

    # Determine whether the accident occurred on a slope aspect
    # identified as critical in the avalanche bulletin.
    acc["in_critical_aspect"] = [
        aspect_in_critical(a, c)
        for a, c in zip((
            acc["aspect"],
            acc["critical_aspects"]))
    ]

    # Determine whether the accident occurred within the critical
    # elevation range specified by the avalanche bulletin.
    acc["in_critical_elevation"] = [
        elevation_in_critical(e, lo, hi)
        for e, lo, hi in zip(
            acc["elevation"],
            acc["critical_elev_min"],
            acc["critical_elev_max"])
    ]

    # Remove intermediate spatial and bulletin attributes while
    # retaining the derived critical slope indicators.
    accidents_tbl = acc.drop(
        columns=["geometry", "critical_aspects", "critical_elev_min", "critical_elev_max"],
        errors="ignore",
    )

    # ------------------------------------------------------------------
    # 5. IMIS station-day features
    # ------------------------------------------------------------------

    # Load daily snow measurements from IMIS. Temperature and wind
    # measurements are primarily covered by Open-Meteo.
    #
    # An empty station list avoids downloading the multi-gigabyte
    # historical dataset containing 30-minute measurements.
    station_day = build_station_day_features(
        station_codes=[], start=start, end=end, force=False
    )

    # Retain relevant snow and meteorological features.
    # Optional columns are selected only if they are available.
    keep = [
        c
        for c in [
            "station_code",
            "date",
            "hs",       # Total snow depth
            "hn_1d",    # New snow over one day
            "hn_3d",    # New snow over three days
            "ta_mean",  # Mean air temperature
            "ta_max",   # Maximum air temperature
            "ta_min",   # Minimum air temperature
            "vw_mean",  # Mean wind speed
            "vw_max",   # Maximum wind speed
        ]
        if c in station_day.columns
    ]
    station_day = station_day[keep]
    log["station_day_rows"] = len(station_day)

    # ------------------------------------------------------------------
    # 6. Aggregate station-day measurements into region-day features
    # ------------------------------------------------------------------

    # Associate each daily station observation with its warning region.
    sd = station_day.merge(
        stations_tbl[["station_code", "region_id"]], on="station_code", how="left"
    )

    # Exclude observations from stations without an assigned region.
    sd = sd.dropna(subset=["region_id"])

    # Define aggregation methods for regional snow measurements
    # and count the number of contributing monitoring stations.
    agg_map = {
        "hs_mean": ("hs", "mean"),
        "hn_1d_mean": ("hn_1d", "mean"),
        "hn_3d_mean": ("hn_3d", "mean"),
        "n_stations": ("station_code", "nunique"),
    }

    # Include optional meteorological measurements when available.
    if "ta_mean" in sd.columns:
        agg_map["ta_mean"] = ("ta_mean", "mean")
    if "vw_max" in sd.columns:
        agg_map["vw_max"] = ("vw_max", "max")

    # Aggregate station-level measurements to one record per region and date.
    region_meteo = sd.groupby(["date", "region_id"], as_index=False).agg(**agg_map)

    # Maintain a consistent output schema even when temperature
    # or wind measurements are unavailable.
    if "ta_mean" not in region_meteo.columns:
        region_meteo["ta_mean"] = np.nan
    if "vw_max" not in region_meteo.columns:
        region_meteo["vw_max"] = np.nan

    # ------------------------------------------------------------------
    # 7. Open-Meteo weather data
    # ------------------------------------------------------------------

    if fetch_weather:
        # Retrieve historical weather data for the warning regions.
        weather = fetch_weather_for_regions(regions_tbl, start=start, end=end)
    else:
        # Reuse previously downloaded weather data when available
        # to avoid unnecessary API requests.
        weather_path = PROCESSED / "weather_day.parquet"
        weather = pd.read_parquet(weather_path) if weather_path.exists() else pd.DataFrame()
    log["weather_rows"] = len(weather)

    # ------------------------------------------------------------------
    # 8. Public holidays
    # ------------------------------------------------------------------

    # Load holiday dates for the predefined observation years.
    holidays = load_holidays(years=list(range(2021, 2028)))

    # Normalize timestamps and use a set for efficient date matching.
    holiday_dates = set(holidays["date"].dt.normalize()) if not holidays.empty else set()

    log["holiday_days"] = len(holiday_dates)

    # ------------------------------------------------------------------
    # 9. Construct the region-day fact table
    # ------------------------------------------------------------------

    # Use avalanche bulletin records as the foundation of the fact
    # table, with region_id and date as the intended composite key.

    # Integrate aggregated regional snow and station measurements.
    fact = bulletin.merge(regions_tbl[["region_id", "major_region"]], on="region_id", how="left")

    # Integrate historical weather features where available.
    fact = fact.merge(region_meteo, on=["date", "region_id"], how="left")
    if not weather.empty:
        wcols = [
            c
            for c in [
                "region_id",
                "date",
                "t_max",
                "t_min",
                "precip",
                "snowfall",
                "wind_max",
                "sunshine_s",
            ]
            if c in weather.columns
        ]
        fact = fact.merge(weather[wcols], on=["date", "region_id"], how="left")

    # Ensure all expected weather columns exist, even when weather
    # retrieval was disabled or measurements are unavailable.
    for col in [
        "t_max",
        "t_min",
        "precip",
        "snowfall",
        "wind_max",
        "sunshine_s",
    ]:
        if col not in fact.columns:
            fact[col] = np.nan

    # Derive calendar-based features that may be associated with
    # recreational activity and exposure to avalanche conditions.
    fact["is_weekend"] = (fact["date"].dt.dayofweek >= 5).astype(int)
    fact["is_holiday"] = fact["date"].dt.normalize().isin(holiday_dates).astype(int)

    # ------------------------------------------------------------------
    # 10. Accident outcome variables
    # ------------------------------------------------------------------

    # Count the number of recorded accidents for each region and date.
    acc_counts = (
        accidents_tbl.groupby(
            ["date", "region_id"],
            as_index=False,
        )
        .size()
        .rename(columns={"size": "n_accidents"})
    )

    # Merge accident counts into the fact table while preserving
    # region-day observations without recorded accidents.
    fact = fact.merge(
        acc_counts,
        on=["date", "region_id"],
        how="left",
    )

    # Treat region-days without matching accident records as having
    # zero recorded accidents.
    fact["n_accidents"] = (
        fact["n_accidents"].fillna(0).astype(int)
    )

    # Create a binary target variable for statistical analysis
    # and classification models.
    #
    # 1 = At least one recorded avalanche accident
    # 0 = No recorded avalanche accident
    fact["accident_occurred"] = (
        fact["n_accidents"] > 0
    ).astype(int)

    # ------------------------------------------------------------------
    # 11. Integration statistics and data quality
    # ------------------------------------------------------------------

    # Record the total number of region-day observations.
    log["region_day_rows"] = len(fact)

    # Count observations with at least one recorded accident.
    log["region_day_positives"] = int(
        fact["accident_occurred"].sum()
    )

    # Calculate the proportion of positive observations to assess
    # class imbalance in the final dataset.
    log["positive_rate"] = (
        float(fact["accident_occurred"].mean())
        if len(fact)
        else None
    )

    # Calculate the proportion of region-day observations without
    # corresponding aggregated IMIS station measurements.
    log["regions_without_station_share"] = (
        float(fact["n_stations"].isna().mean())
        if len(fact)
        else None
    )

    # ------------------------------------------------------------------
    # 12. Persist processed datasets
    # ------------------------------------------------------------------

    # Store integrated and intermediate datasets in Parquet format
    # for efficient storage and subsequent analytical processing.
    regions_tbl.to_parquet(
        PROCESSED / "regions.parquet",
        index=False,
    )

    bulletin.to_parquet(
        PROCESSED / "bulletin_region_day.parquet",
        index=False,
    )

    problems.to_parquet(
        PROCESSED / "bulletin_problem.parquet",
        index=False,
    )

    stations_tbl.drop(
        columns=["geometry"],
        errors="ignore",
    ).to_parquet(
        PROCESSED / "stations.parquet",
        index=False,
    )

    station_day.to_parquet(
        PROCESSED / "station_day.parquet",
        index=False,
    )

    accidents_tbl.to_parquet(
        PROCESSED / "accidents.parquet",
        index=False,
    )

    # Persist weather data only when available to avoid overwriting
    # previously cached data with an empty dataset.
    if not weather.empty:
        weather.to_parquet(
            PROCESSED / "weather_day.parquet",
            index=False,
        )

    holidays.to_parquet(
        PROCESSED / "holidays.parquet",
        index=False,
    )

    # Persist the final fact table used for downstream analysis.
    fact.to_parquet(
        PROCESSED / "region_day.parquet",
        index=False,
    )

    # Write integration statistics as a human-readable JSON file
    # to support reproducibility and data quality assessments.
    INTEGRATION_LOG.write_text(
        json.dumps(log, indent=2, default=str)
    )

    # Ensure the output directory for analytical figures exists.
    FIGURES.mkdir(parents=True, exist_ok=True)

    # ------------------------------------------------------------------
    # 13. Return integrated datasets
    # ------------------------------------------------------------------

    # Return all processed tables for further analysis without
    # requiring them to be loaded again from disk.
    return {
        "regions": regions_tbl,
        "bulletin_region_day": bulletin,
        "bulletin_problem": problems,
        "stations": stations_tbl.drop(
            columns=["geometry"],
            errors="ignore",
        ),
        "station_day": station_day,
        "accidents": accidents_tbl,
        "weather_day": weather,
        "holidays": holidays,
        "region_day": fact,
        "log": pd.Series(log),
    }